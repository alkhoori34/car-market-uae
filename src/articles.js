export function formatArticleDate(iso, en = BROWSER_EN) {
  return new Intl.DateTimeFormat(en ? "en-GB" : "ar-AE", { day: "numeric", month: "long", year: "numeric" }).format(new Date(iso + "T12:00:00Z"));
}
